def build_tool_group_map() -> dict[str, str]:
    """Return ``{tool_name: group_name}`` derived from :data:`TOOL_GROUPS`."""
    mapping: dict[str, str] = {}
    for group_name, spec in TOOL_GROUPS.items():
        for tool in spec["tools"]:
            mapping[tool] = group_name
    return mapping


TOOL_GROUP_MAP: dict[str, str] = build_tool_group_map()


def group_of(tool_name: str) -> str:
    """Group a tool belongs to; unknown tools fall back to ``basic``."""
    return TOOL_GROUP_MAP.get(tool_name, "basic")


def is_always_active(group_name: str) -> bool:
    return bool(TOOL_GROUPS.get(group_name, {}).get("always_active", False))


def active_groups_for_query(query: str) -> list[str]:
    """Keyword pre-activation used at step 1 only.

    Returns the on-demand groups whose keywords appear in *query*. Because
    ``reset_equipped_tools`` is absolute, a later model call re-derives the
    active set; pre-activation is a step-1 latency optimization, not a
    persistent state.
    """
    if not query:
        return []
    lowered = query.lower()
    hits: list[str] = []
    for group_name, spec in TOOL_GROUPS.items():
        if spec.get("always_active"):
            continue
        if any(k in lowered for k in spec.get("keywords", set())):
            hits.append(group_name)
    return hits


def validate_against_registry(registered: set[str]) -> dict[str, list[str]]:
    """Compare the group table with the live tool registry.

    ``missing``: registered tools with no group assignment — they would
    silently land in the always-active ``basic`` group and inflate the schema.
    ``extra``: group entries absent from the registry (stale rows).
    """
    return {
        "missing": sorted(t for t in registered if t not in TOOL_GROUP_MAP),
        "extra": sorted(t for t in TOOL_GROUP_MAP if t not in registered),
    }


