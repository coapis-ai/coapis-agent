"""Tool group definitions for on-demand tool activation (ToolManager).

Maps every registered builtin tool to a named group so the toolkit keeps only
the core group active at step 1 and lets the model equip the rest through the
upstream ``reset_equipped_tools`` meta tool.

Measured on the dev runtime (2026-10-16, 33 builtin tools, 31223 chars of
function schema):
  - parameter descriptions 30.9%, function descriptions 17.3%, structure 8.6%.
  - trimming descriptions alone saves 10-13%; *grouping* is the primary lever
    (``browser_use`` alone is 9078 chars = 29% of the builtin schema).
  - the catalog is generated by upstream: ``get_json_schemas`` builds a pydantic
    model whose field descriptions are the group descriptions, measured at
    ~97 chars per group (11-12 groups ≈ 1.1K chars). Keep descriptions short.

``reset_equipped_tools`` has ABSOLUTE semantics — groups absent from the call
are deactivated — so keyword pre-activation only shapes step 1 and every
later call re-derives the active set from scratch.

Keep :data:`TOOL_GROUPS` in sync with ``coapis.agents.tools.registry``;
``validate_against_registry`` is the runtime guard and
``tests/agents/test_tool_groups.py`` fails the build on drift.
"""

